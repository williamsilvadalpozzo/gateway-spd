-- Fila persistente do redirecionador HTTP.
-- Oracle 12c ou superior, por causa de FETCH FIRST e SKIP LOCKED no consumo.

CREATE SEQUENCE SQ_GATEWAY_REQUISICAO_HTTP
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE GATEWAY_REQUISICAO_HTTP (
    ID                      NUMBER            NOT NULL,
    CHAVE_IDEMPOTENCIA      VARCHAR2(200 CHAR),
    ASSINCRONO              NUMBER(1)         NOT NULL,
    PROCESSO                VARCHAR2(200 CHAR),
    LOTE                    VARCHAR2(400 CHAR),
    STATUS                  VARCHAR2(20)      NOT NULL,
    INSTANCIA               VARCHAR2(200 CHAR),
    HEARTBEAT_EM            TIMESTAMP(6),
    METODO                  VARCHAR2(16)      NOT NULL,
    URL                     VARCHAR2(4000 CHAR) NOT NULL,
    PARAMETROS_JSON         CLOB,
    HEADERS_JSON            CLOB,
    TIPO_CORPO              VARCHAR2(30)      NOT NULL,
    CONTENT_TYPE_REQUISICAO VARCHAR2(255 CHAR),
    CORPO_REQUISICAO        BLOB,
    TIPO_RETORNO            VARCHAR2(20)      NOT NULL,
    TIMEOUT_SEGUNDOS        NUMBER(10)        NOT NULL,
    CERTIFICADO_ARQUIVO     VARCHAR2(255 CHAR),
    USAR_CERTIFICADO        NUMBER(1)         NOT NULL,
    CERTIFICADOS_DESTINO    CLOB,
    HTTP_STATUS             NUMBER(3),
    HEADERS_RESPOSTA_JSON   CLOB,
    CONTENT_TYPE_RESPOSTA   VARCHAR2(255 CHAR),
    CHARSET_RESPOSTA        VARCHAR2(40 CHAR),
    CORPO_RESPOSTA          BLOB,
    TAMANHO_RESPOSTA        NUMBER,
    MENSAGEM_ERRO           CLOB,
    CRIADO_EM               TIMESTAMP(6)      NOT NULL,
    INICIADO_EM             TIMESTAMP(6),
    FINALIZADO_EM           TIMESTAMP(6),
    CONSTRAINT PK_GATEWAY_REQUISICAO_HTTP PRIMARY KEY (ID),
    CONSTRAINT CK_GW_REQ_HTTP_STATUS CHECK (
        STATUS IN ('PENDENTE', 'EM_EXECUCAO', 'FINALIZADO', 'ERRO', 'TIMEOUT')
    ),
    CONSTRAINT CK_GW_REQ_HTTP_ASSINC CHECK (ASSINCRONO IN (0, 1)),
    CONSTRAINT CK_GW_REQ_HTTP_CERT CHECK (USAR_CERTIFICADO IN (0, 1))
);

CREATE UNIQUE INDEX UK_GW_REQ_HTTP_CHAVE
    ON GATEWAY_REQUISICAO_HTTP (CHAVE_IDEMPOTENCIA);

CREATE INDEX IX_GW_REQ_HTTP_FILA
    ON GATEWAY_REQUISICAO_HTTP (ASSINCRONO, STATUS, ID);

CREATE INDEX IX_GW_REQ_HTTP_LOTE
    ON GATEWAY_REQUISICAO_HTTP (PROCESSO, LOTE);
