CREATE SEQUENCE SQ_GATEWAY_PROCESSO_LOG
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE GATEWAY_PROCESSO_LOG (
    ID            NUMBER              NOT NULL,
    TOKEN         VARCHAR2(36)        NOT NULL,
    DATA_CHAMADA  TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    ORIGEM        VARCHAR2(20)        NOT NULL,
    CHAMADA       VARCHAR2(4000 CHAR) NOT NULL,
    PARAMETROS    CLOB,
    CONSTRAINT PK_GATEWAY_PROCESSO_LOG PRIMARY KEY (ID)
);

CREATE OR REPLACE TRIGGER TRG_GATEWAY_PROCESSO_LOG_ID
BEFORE INSERT ON GATEWAY_PROCESSO_LOG
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        SELECT SQ_GATEWAY_PROCESSO_LOG.NEXTVAL
          INTO :NEW.ID
          FROM DUAL;
    END IF;
END;
